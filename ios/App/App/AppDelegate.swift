    // ── @capacitor/push-notifications (APNs) — required forwarding hooks ──────
    // Without these three, the JS-side PushNotifications.addListener('registration'/
    // 'registrationError'/'pushNotificationReceived') callbacks never fire — the
    // plugin is a thin wrapper over these UIApplicationDelegate calls.
    func application(_ application: UIApplication, didRegisterForRemoteNotificationsWithDeviceToken deviceToken: Data) {
        NotificationCenter.default.post(name: .capacitorDidRegisterForRemoteNotifications, object: deviceToken)
    }

    func application(_ application: UIApplication, didFailToRegisterForRemoteNotificationsWithError error: Error) {
        NotificationCenter.default.post(name: .capacitorDidFailToRegisterForRemoteNotifications, object: error)
    }

    // Capacitor 8 publishes exactly TWO remote-notification names,
    // capacitorDidRegisterForRemoteNotifications and
    // capacitorDidFailToRegisterForRemoteNotifications (verified against
    // Capacitor.swiftmodule). There is no "did receive" name and no
